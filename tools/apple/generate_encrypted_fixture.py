"""Generate an owned CBCS fixture for Media3/JNI-routing regression tests.

Only synthetic tones generated by generate_test_audio.py are inputs. The key is
test data, unrelated to Apple accounts or Apple runtime keys. Requires openssl.
"""
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
KEY = bytes(range(16))
IV = bytes(16)
KID = bytes(range(16, 32))


def box(name, data):
    return (len(data) + 8).to_bytes(4, 'big') + name + data


def children(data):
    p = 0
    while p < len(data):
        n = int.from_bytes(data[p:p + 4], 'big')
        assert n >= 8 and n <= len(data) - p
        yield data[p + 4:p + 8], data[p + 8:p + n]
        p += n


def protect(entry, kid):
    frma = box(b'frma', b'alac')
    schm = box(b'schm', bytes(4) + b'cbcs' + bytes.fromhex('00010000'))
    tenc = box(b'tenc', bytes(4) + bytes([0, 0, 1, 0]) + kid + bytes([16]) + IV)
    return box(b'enca', entry + box(b'sinf', frma + schm + box(b'schi', tenc)))


def rewrite(kind, value):
    if kind == b'stsd':
        entries = list(children(value[8:])); assert len(entries) == 1 and entries[0][0] == b'alac'
        value = value[:4] + (2).to_bytes(4, 'big') + protect(entries[0][1], bytes(range(32, 48))) + protect(entries[0][1], KID)
    elif kind == b'trex':
        value = value[:8] + (2).to_bytes(4, 'big') + value[12:]
    elif kind in {b'moov', b'trak', b'mdia', b'minf', b'stbl', b'mvex'}:
        value = b''.join(rewrite(k, v) for k, v in children(value))
    return box(kind, value)


def main():
    source = ROOT / 'dsp/src/test/resources/audio/owned-24bit-192000-2ch.m4a'
    data = source.read_bytes()
    sizes = []
    for k, v in children(data):
        if k == b'moof':
            for tk, tv in children(v):
                if tk == b'traf':
                    for sk, sv in children(tv):
                        if sk == b'trun':
                            flags = int.from_bytes(sv[:4], 'big') & 0xffffff
                            assert flags == 0x201  # data_offset and per-sample size
                            count = int.from_bytes(sv[4:8], 'big')
                            sizes = [int.from_bytes(sv[12 + i * 4:16 + i * 4], 'big') for i in range(count)]
    assert len(sizes) == 2
    output = bytearray()
    for k, v in children(data):
        if k == b'moof':
            parts = []
            for tk, tv in children(v):
                if tk == b'traf':
                    sub = []
                    senc = box(b'senc', bytes(4) + len(sizes).to_bytes(4, 'big'))
                    for sk, sv in children(tv):
                        if sk == b'trun':
                            sv = sv[:8] + (int.from_bytes(sv[8:12], 'big') + len(senc)).to_bytes(4, 'big') + sv[12:]
                        sub.append(box(sk, sv))
                    tv = b''.join(sub) + senc
                parts.append(box(tk, tv))
            output.extend(box(k, b''.join(parts)))
        elif k == b'mdat':
            assert sum(sizes) == len(v)
            encoded = bytearray(); p = 0
            for n in sizes:
                sample = v[p:p + n]; aligned = n // 16 * 16
                encrypted = subprocess.check_output(['openssl', 'enc', '-aes-128-cbc', '-K', KEY.hex(), '-iv', IV.hex(), '-nopad'], input=sample[:aligned])
                encoded.extend(encrypted + sample[aligned:]); p += n
            output.extend(box(k, encoded))
        else:
            output.extend(rewrite(k, v))
    target = ROOT / 'app/src/test/resources/audio'
    (target / 'owned-apple-alac.m4a').write_bytes(data)
    (target / 'owned-apple-cbcs-alac.mp4').write_bytes(output)
    print('Generated owned CBCS test fixture:', len(output), 'bytes')


if __name__ == '__main__':
    main()
